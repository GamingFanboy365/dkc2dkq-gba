#!/usr/bin/env python3
"""Turns a KEYS script (tools/common/tool_common.h) into a C table for the
GBA's test builds (DKC2_TEST_KEYS): g_test_keys[][2] = {frames, SNES joypad}.

  keys_to_c.py SCRIPT_FILE OUT.h
"""
import sys

BITS = {"a": 0x0080, "b": 0x8000, "x": 0x0040, "y": 0x4000, "l": 0x0020, "r": 0x0010,
        "up": 0x0800, "down": 0x0400, "left": 0x0200, "right": 0x0100, "select": 0x2000,
        "start": 0x1000}

script = open(sys.argv[1]).read().strip()
rows = []
for part in filter(None, script.split(",")):
    n, keys = part.split(":")
    if n == "*":
        n = "65535"
    bits = 0
    for k in keys.split("+"):
        if k != "-":
            bits |= BITS[k.lower()]
    rows.append((int(n), bits))
with open(sys.argv[2], "w") as f:
    f.write("// Generated by tools/keys_to_c.py. Don't edit.\n")
    f.write("static const uint16_t g_test_keys[][2] = {\n")
    for n, bits in rows:
        f.write(f"  {{{n}, 0x{bits:04x}}},\n")
    f.write("};\n")
