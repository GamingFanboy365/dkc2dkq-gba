/*
 * gbarun - minimal headless GBA runner built on libmgba.
 *
 * Loads a ROM, optionally restores a savestate, runs a number of frames while
 * feeding a scripted joypad sequence, writes PNG screenshots at chosen frames
 * and optionally writes a savestate at the end (or at a chosen frame).
 *
 * Usage:
 *   gbarun [options] ROM
 *
 * Options (each also settable through the environment variable in brackets;
 * a command-line option wins over the environment):
 *   -n FRAMES   total frames to run                          [FRAMES]
 *               default: length of the key script, or 600 if there is none
 *   -k SCRIPT   key script                                   [KEYS]
 *   -s LIST     frames at which to save screenshots          [SHOTS]
 *   -o DIR      output directory for screenshots (default .) [OUT]
 *   -p PREFIX   screenshot filename prefix (default "shot")  [PREFIX]
 *   -l FILE     savestate to load before running             [STATE]
 *   -w FILE     savestate to write                           [STATE_OUT]
 *   -W FRAME    frame after which to write -w (default: end) [STATE_OUT_AT]
 *   -S FILE     battery save file (copied in memory; the file
 *               is never modified)                           [SAVE]
 *   -m          at every shot frame also dump work RAM: DIR/PREFIX_%06d.ewram
 *               (256 KiB from 0x02000000) and .iwram (32 KiB from
 *               0x03000000)                                  [MEMDUMP=1]
 *   -q          quiet (no per-shot log lines)
 *
 * What the game prints through mGBA's debug registers (0x04FFF600) goes to
 * stdout, a line per message.
 *
 * Key script: comma-separated segments "COUNT:KEYS", where COUNT is a number
 * of frames and KEYS is "-" (nothing held) or key names joined by '+':
 *   A B L R START SELECT UP DOWN LEFT RIGHT  (case-insensitive; U/D/LT/RT ok)
 * Example: "60:-,10:A,30:-,120:RIGHT+B,5:RIGHT+B+A"
 * Segments run back to back from frame 0 (frame numbers are relative to the
 * start of the run, also when a savestate was loaded). After the script ends
 * no key is held.
 *
 * Shot list: comma-separated frame numbers or ranges "FIRST-LAST/STEP"
 * (STEP defaults to 1), e.g. "100,200,300-400/20". Frame N means "after N
 * frames have been emulated"; 0 is the state right after loading. Files are
 * named DIR/PREFIX_%06d.png.
 */
/* flags.h (generated by the libmgba build) must come first: it sets
 * ENABLE_VFS, USE_PNG etc., which gate parts of the public headers. */
#include <mgba/flags.h>
#include <mgba/core/core.h>
#include <mgba/core/config.h>
#include <mgba/core/log.h>
#include <mgba/core/serialize.h>
#include <mgba-util/vfs.h>

#include <ctype.h>
#include <errno.h>
#include <fcntl.h>
#include <stdbool.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <strings.h>
#include <sys/stat.h>
#include <unistd.h>

/* GBA KEYINPUT bit numbers, which is also the bit order core->setKeys() uses. */
enum {
	KEY_A = 0, KEY_B = 1, KEY_SELECT = 2, KEY_START = 3,
	KEY_RIGHT = 4, KEY_LEFT = 5, KEY_UP = 6, KEY_DOWN = 7,
	KEY_R = 8, KEY_L = 9,
};

struct Segment {
	unsigned frames;
	uint32_t keys;
};

struct Range {
	unsigned first, last, step;
};

static void die(const char* fmt, const char* arg) {
	fprintf(stderr, "gbarun: ");
	fprintf(stderr, fmt, arg);
	fputc('\n', stderr);
	exit(1);
}

static uint32_t parseKey(const char* name) {
	static const struct {
		const char* name;
		int key;
	} keys[] = {
		{ "A", KEY_A }, { "B", KEY_B },
		{ "L", KEY_L }, { "R", KEY_R },
		{ "START", KEY_START }, { "ST", KEY_START },
		{ "SELECT", KEY_SELECT }, { "SEL", KEY_SELECT },
		{ "UP", KEY_UP }, { "U", KEY_UP },
		{ "DOWN", KEY_DOWN }, { "D", KEY_DOWN },
		{ "LEFT", KEY_LEFT }, { "LT", KEY_LEFT },
		{ "RIGHT", KEY_RIGHT }, { "RT", KEY_RIGHT },
	};
	size_t i;
	for (i = 0; i < sizeof(keys) / sizeof(*keys); ++i) {
		if (strcasecmp(name, keys[i].name) == 0) {
			return 1u << keys[i].key;
		}
	}
	die("unknown key name '%s'", name);
	return 0;
}

static unsigned parseUnsigned(const char* s, const char* what) {
	char* end;
	errno = 0;
	unsigned long v = strtoul(s, &end, 10);
	if (errno || end == s || *end) {
		die("bad number in %s", what);
	}
	return (unsigned) v;
}

/* Parses the key script; returns the number of segments (array in *out). */
static size_t parseScript(const char* script, struct Segment** out) {
	size_t n = 0, cap = 16;
	struct Segment* segs = malloc(cap * sizeof(*segs));
	char* copy = strdup(script);
	char* save1;
	char* seg;
	for (seg = strtok_r(copy, ",", &save1); seg; seg = strtok_r(NULL, ",", &save1)) {
		while (isspace((unsigned char) *seg)) {
			++seg;
		}
		if (!*seg) {
			continue;
		}
		char* colon = strchr(seg, ':');
		if (!colon) {
			die("key segment '%s' lacks COUNT:", seg);
		}
		*colon = '\0';
		struct Segment s = { parseUnsigned(seg, "key script"), 0 };
		char* keys = colon + 1;
		if (strcmp(keys, "-") != 0 && *keys) {
			char* save2;
			char* k;
			for (k = strtok_r(keys, "+", &save2); k; k = strtok_r(NULL, "+", &save2)) {
				s.keys |= parseKey(k);
			}
		}
		if (n == cap) {
			cap *= 2;
			segs = realloc(segs, cap * sizeof(*segs));
		}
		segs[n++] = s;
	}
	free(copy);
	*out = segs;
	return n;
}

static size_t parseShots(const char* list, struct Range** out) {
	size_t n = 0, cap = 16;
	struct Range* r = malloc(cap * sizeof(*r));
	char* copy = strdup(list);
	char* save;
	char* item;
	for (item = strtok_r(copy, ",", &save); item; item = strtok_r(NULL, ",", &save)) {
		while (isspace((unsigned char) *item)) {
			++item;
		}
		if (!*item) {
			continue;
		}
		struct Range x;
		char* slash = strchr(item, '/');
		x.step = 1;
		if (slash) {
			*slash = '\0';
			x.step = parseUnsigned(slash + 1, "shot step");
			if (!x.step) {
				die("shot step must be > 0 (%s)", item);
			}
		}
		char* dash = strchr(item, '-');
		if (dash) {
			*dash = '\0';
			x.first = parseUnsigned(item, "shot list");
			x.last = parseUnsigned(dash + 1, "shot list");
		} else {
			x.first = x.last = parseUnsigned(item, "shot list");
		}
		if (n == cap) {
			cap *= 2;
			r = realloc(r, cap * sizeof(*r));
		}
		r[n++] = x;
	}
	free(copy);
	*out = r;
	return n;
}

static bool wantShot(const struct Range* r, size_t n, unsigned frame) {
	size_t i;
	for (i = 0; i < n; ++i) {
		if (frame >= r[i].first && frame <= r[i].last && (frame - r[i].first) % r[i].step == 0) {
			return true;
		}
	}
	return false;
}

static void shoot(struct mCore* core, const char* dir, const char* prefix, unsigned frame, bool quiet) {
	char path[4096];
	snprintf(path, sizeof(path), "%s/%s_%06u.png", dir, prefix, frame);
	struct VFile* vf = VFileOpen(path, O_CREAT | O_TRUNC | O_WRONLY);
	if (!vf) {
		die("cannot write %s", path);
	}
	bool ok = mCoreTakeScreenshotVF(core, vf);
	vf->close(vf);
	if (!ok) {
		die("screenshot failed for %s", path);
	}
	if (!quiet) {
		printf("shot %s\n", path);
	}
}

/* mkdir -p */
static void makeDirs(const char* path) {
	char* p = strdup(path);
	char* q;
	for (q = p + 1; *q; ++q) {
		if (*q == '/') {
			*q = '\0';
			mkdir(p, 0777);
			*q = '/';
		}
	}
	mkdir(p, 0777);
	free(p);
}

static void dumpRegion(struct mCore* core, const char* dir, const char* prefix, unsigned frame,
                       const char* ext, uint32_t base, uint32_t size) {
	char path[4096];
	snprintf(path, sizeof(path), "%s/%s_%06u.%s", dir, prefix, frame, ext);
	FILE* f = fopen(path, "wb");
	if (!f) {
		die("cannot write %s", path);
	}
	uint32_t i;
	for (i = 0; i < size; i += 4) {
		uint32_t w = core->busRead32(core, base + i);
		uint8_t b[4] = { w, w >> 8, w >> 16, w >> 24 };
		fwrite(b, 1, 4, f);
	}
	fclose(f);
}

static void dumpMemory(struct mCore* core, const char* dir, const char* prefix, unsigned frame) {
	dumpRegion(core, dir, prefix, frame, "ewram", 0x02000000, 0x40000);
	dumpRegion(core, dir, prefix, frame, "iwram", 0x03000000, 0x8000);
}

static void writeState(struct mCore* core, const char* path) {
	struct VFile* vf = VFileOpen(path, O_CREAT | O_TRUNC | O_RDWR);
	if (!vf) {
		die("cannot write savestate %s", path);
	}
	if (!mCoreSaveStateNamed(core, vf, SAVESTATE_SAVEDATA | SAVESTATE_RTC | SAVESTATE_METADATA)) {
		die("saving state to %s failed", path);
	}
	vf->close(vf);
	printf("state %s\n", path);
}

static void quietLog(struct mLogger* logger, int category, enum mLogLevel level, const char* format, va_list args) {
	(void) logger;
	/* What the game prints through mGBA's debug registers goes to stdout. */
	const char* id = mLogCategoryId(category);
	if (id && strcmp(id, "gba.debug") == 0) {
		vprintf(format, args);
		putchar('\n');
		fflush(stdout);
		return;
	}
	if (level & (mLOG_FATAL | mLOG_ERROR)) {
		vfprintf(stderr, format, args);
		fputc('\n', stderr);
	}
}

static const char* opt(const char* cli, const char* env) {
	if (cli) {
		return cli;
	}
	const char* v = getenv(env);
	return (v && *v) ? v : NULL;
}

int main(int argc, char** argv) {
	const char *framesArg = NULL, *keysArg = NULL, *shotsArg = NULL, *outArg = NULL, *prefixArg = NULL;
	const char *stateArg = NULL, *stateOutArg = NULL, *stateOutAtArg = NULL, *saveArg = NULL;
	bool quiet = false;
	bool memDump = false;
	int c;
	while ((c = getopt(argc, argv, "n:k:s:o:p:l:w:W:S:mqh")) != -1) {
		switch (c) {
		case 'n': framesArg = optarg; break;
		case 'k': keysArg = optarg; break;
		case 's': shotsArg = optarg; break;
		case 'o': outArg = optarg; break;
		case 'p': prefixArg = optarg; break;
		case 'l': stateArg = optarg; break;
		case 'w': stateOutArg = optarg; break;
		case 'W': stateOutAtArg = optarg; break;
		case 'S': saveArg = optarg; break;
		case 'm': memDump = true; break;
		case 'q': quiet = true; break;
		default:
			fprintf(stderr, "usage: %s [-n frames] [-k keys] [-s shots] [-o dir] [-p prefix] "
			                "[-l state] [-w state_out] [-W frame] [-S savefile] [-m] [-q] ROM\n", argv[0]);
			return c == 'h' ? 0 : 1;
		}
	}
	if (optind != argc - 1) {
		fprintf(stderr, "gbarun: expected exactly one ROM path (see -h)\n");
		return 1;
	}
	const char* romPath = argv[optind];
	framesArg = opt(framesArg, "FRAMES");
	keysArg = opt(keysArg, "KEYS");
	shotsArg = opt(shotsArg, "SHOTS");
	outArg = opt(outArg, "OUT");
	prefixArg = opt(prefixArg, "PREFIX");
	stateArg = opt(stateArg, "STATE");
	stateOutArg = opt(stateOutArg, "STATE_OUT");
	stateOutAtArg = opt(stateOutAtArg, "STATE_OUT_AT");
	saveArg = opt(saveArg, "SAVE");
	if (getenv("MEMDUMP") && strcmp(getenv("MEMDUMP"), "1") == 0) {
		memDump = true;
	}
	const char* outDir = outArg ? outArg : ".";
	const char* prefix = prefixArg ? prefixArg : "shot";

	struct Segment* segs = NULL;
	size_t nSegs = keysArg ? parseScript(keysArg, &segs) : 0;
	unsigned scriptLen = 0;
	size_t i;
	for (i = 0; i < nSegs; ++i) {
		scriptLen += segs[i].frames;
	}
	struct Range* shots = NULL;
	size_t nShots = shotsArg ? parseShots(shotsArg, &shots) : 0;
	unsigned frames = framesArg ? parseUnsigned(framesArg, "-n") : (nSegs ? scriptLen : 600);
	unsigned stateOutAt = stateOutAtArg ? parseUnsigned(stateOutAtArg, "-W") : frames;
	if (nShots) {
		makeDirs(outDir);
	}

	static struct mLogger logger = { .log = quietLog };
	mLogSetDefaultLogger(&logger);

	struct mCore* core = mCoreFind(romPath);
	if (!core) {
		die("no core accepts %s", romPath);
	}
	core->init(core);
	mCoreInitConfig(core, NULL);
	struct mCoreOptions opts = { .useBios = false, .skipBios = true, .volume = 0x100 };
	mCoreConfigLoadDefaults(&core->config, &opts);
	mCoreLoadConfig(core);

	unsigned w, h;
	core->baseVideoSize(core, &w, &h);
	mColor* video = calloc((size_t) w * h, BYTES_PER_PIXEL);
	core->setVideoBuffer(core, video, w);
	core->setAudioBufferSize(core, 1024);

	if (!mCoreLoadFile(core, romPath)) {
		die("failed to load ROM %s", romPath);
	}
	if (saveArg && !mCoreLoadSaveFile(core, saveArg, true)) {
		die("failed to load save file %s", saveArg);
	}
	core->reset(core);

	if (stateArg) {
		struct VFile* vf = VFileOpen(stateArg, O_RDONLY);
		if (!vf) {
			die("cannot open savestate %s", stateArg);
		}
		if (!mCoreLoadStateNamed(core, vf, SAVESTATE_SAVEDATA | SAVESTATE_RTC | SAVESTATE_METADATA)) {
			die("loading savestate %s failed", stateArg);
		}
		vf->close(vf);
	}

	/* Frame 0: whatever is in the video buffer right after load (blank on a
	 * cold boot; mGBA does not restore the framebuffer from a state unless the
	 * state carries a screenshot). */
	if (wantShot(shots, nShots, 0)) {
		shoot(core, outDir, prefix, 0, quiet);
		if (memDump) {
			dumpMemory(core, outDir, prefix, 0);
		}
	}
	if (stateOutArg && stateOutAt == 0) {
		writeState(core, stateOutArg);
	}

	size_t seg = 0;
	unsigned segLeft = nSegs ? segs[0].frames : 0;
	unsigned f;
	for (f = 1; f <= frames; ++f) {
		while (seg < nSegs && segLeft == 0) {
			++seg;
			segLeft = seg < nSegs ? segs[seg].frames : 0;
		}
		uint32_t keys = 0;
		if (seg < nSegs) {
			keys = segs[seg].keys;
			--segLeft;
		}
		core->setKeys(core, keys);
		core->runFrame(core);
		if (wantShot(shots, nShots, f)) {
			shoot(core, outDir, prefix, f, quiet);
			if (memDump) {
				dumpMemory(core, outDir, prefix, f);
			}
		}
		if (stateOutArg && f == stateOutAt) {
			writeState(core, stateOutArg);
		}
	}

	core->deinit(core);
	free(video);
	free(segs);
	free(shots);
	return 0;
}
